                - Шпион угадал слово: Шпион получает +2 очка, Художники — 0.
                - Шпион ошибся: Каждый Художник получает +1 очко, Шпион — 0.

                Голосование:
                Если Шпион не стал выкрикивать слово, начинается голосование. Игроки обсуждают получившийся рисунок и на счет «три» одновременно указывают на того, кого подозревают.
                - Победа Художников: Если большинство указало на Шпиона, каждый Художник получает +1 очко, Шпион — 0.
                - Победа Шпиона: Если Художники ошиблись и большинство указало на мирного игрока, Шпион получает +1 очко, Художники — 0.

                В конце раунда Ведущий нажимает соответствующие кнопки в приложении, чтобы распределить баллы, и можно начинать новую игру!

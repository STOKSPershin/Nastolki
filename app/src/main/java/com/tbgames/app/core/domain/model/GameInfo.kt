package com.tbgames.app.core.domain.model

data class GameInfo(
    val id: String,
    val name: String,
    val description: String,
    val rules: String,
    val emoji: String,
    val minPlayers: Int,
    val maxPlayers: Int
) {
    companion object {
        val FAKE_ARTIST = GameInfo(
            id = "fake_artist",
            name = "Фейковый художник",
            description = "Один из игроков не знает что рисовать — найдите его!",
            rules = """
                🎨 Подготовка к игре
                Инвентарь: Общий лист бумаги (игровое поле) и средства для рисования. В идеале — маркеры или ручки разных цветов для каждого участника, но подойдет и одна ручка на всех.

                Ведущий: Один из игроков берет на себя управление приложением. Он переключает экраны, объявляет голосование и начисляет очки в конце раунда.

                🎭 Роли и старт
                Приложение показывает всем игрокам общую категорию, к которой относится загаданное слово. Затем участники по очереди тайно смотрят в экран (например, снимая спойлер):
                - Художники (все, кроме одного): видят само загаданное слово.
                - Шпион (один случайный игрок): видит только надпись «Ты — Шпион» и не знает слова.

                ✏️ Процесс рисования
                Игроки по очереди делают свой ход на общем листе бумаги.
                - В свой ход можно нарисовать только одну непрерывную линию. Рисовать нужно строго не отрывая руки или маркера от бумаги. Как только маркер оторвался от листа — ход окончен.
                - По умолчанию игра длится два полных круга, чтобы каждый участник успел провести по две линии (по предварительной договоренности количество кругов можно увеличить).

                🎯 Цели сторон
                - Задача Шпиона: Внимательно следить за чужими штрихами, анализировать рисунок и провести свою линию так, чтобы слиться с толпой и не выдать себя.
                - Задача Художников: Нарисовать свой элемент так, чтобы другие «свои» поняли — он знает загаданное слово. Однако рисовать слишком очевидные детали нельзя, иначе Шпион сразу догадается, о чем речь.

                ⚖️ Финал и начисление очков
                Раунд заканчивается, когда завершены все круги рисования, либо если Художники догадались, кто Шпион, и требуют досрочного голосования.

